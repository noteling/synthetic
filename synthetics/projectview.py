"""Generated read-only Markdown view of a project log (M21 phase 3).

``render`` is a pure function of the log entries (and the source bytes they cite): the same entries give the same
bytes. It reads no clock, home, environment or host path. Nobody edits the view; corrections go through the log.
"""

from __future__ import annotations

from typing import Callable

from . import projectlog

EXCERPT = 256  # bytes of a cited source shown under an intent (r6 §3.3 quote prefix)
TEXT = 600     # bytes of a lesson statement / applies_when / uncertainty / claim shown


def _cut(text, limit: int) -> str:
    data = " ".join(str(text or "").split()).encode("utf-8")
    if len(data) <= limit:
        return data.decode("utf-8")
    return data[:limit].decode("utf-8", "ignore") + "…"


def _md(text: str) -> str:
    # _cut already folded whitespace; keep table/heading characters inert.
    return text.replace("|", "\\|")


_INCOMING = {"refines": "refined by", "carries": "carried by", "context": "context for", "disputes": "disputed by"}


def _links(ref: str, claims: dict, records: dict, *, sources: dict, outgoing: dict) -> list[str]:
    """Lines shown under a claim: later records that refine/carry/dispute it, and what it cites as context
    (proposal: "the view shows the refinement under it")."""
    out = []
    for link in claims[ref]["links"]:
        if link["rel"] == "revises":
            continue  # shown as "now reads" / History
        other = claims.get(link["from"])
        rec = records.get(link["from"].split("#")[0])
        flags = f" [{', '.join(rec['flags'])}]" if rec and rec["flags"] else ""
        text = f": {_md(_cut(other['text'], TEXT))}" if other else ""
        out.append(f"  - {_INCOMING.get(link['rel'], link['rel'])} {link['from']}{text}{flags}")
    for rel, target in outgoing.get(ref, ()):
        src = sources.get(target)
        what = f" (source seq {src['seq']}, {src['role']})" if src else ""
        out.append(f"  - {rel}: {target}{what}")
    return out


def render(entries: list[dict], project: str, source_bytes: Callable[[str], bytes | None] | None = None) -> str:
    """Render the view of ``entries`` (a log prefix). ``source_bytes(id)`` supplies quote excerpts; it returns None
    for a source redacted since (an as-of view must not show bytes that are gone now)."""
    state = projectlog.fold(entries)
    bodies = {e["id"]: e["body"] for e in entries}
    records = state["records"]
    claims = state["claims"]
    intents = sorted((r for r in records.values() if r["kind"] == "intent"), key=lambda r: r["seq"])
    lessons = sorted((r for r in records.values() if r["kind"] == "lesson"), key=lambda r: r["seq"])
    current = [r for r in intents if r["status"] == "current"]
    # Relations leaving a claim (e.g. `context` to a source); incoming ones are in claims[ref]["links"].
    outgoing: dict[str, list[tuple[str, str]]] = {}
    for e in projectlog.active_entries(entries):
        if e["kind"] == "relate" and e["body"].get("rel") != "revises":
            outgoing.setdefault(e["body"].get("from", ""), []).append((e["body"]["rel"], e["body"].get("target", "")))
    counts = {s: sum(1 for r in lessons if r["status"] == s) for s in ("accepted", "proposed", "disputed")}
    out: list[str] = []
    w = out.append

    w(f"# Project memory: {project}")
    w("")
    w(f"Generated from the project log as of seq {state['through']}. Do not edit this file: append to the log "
      "(project_memory_append) and it is rebuilt.")
    w("")
    w(f"Intents current: {len(current)} of {len(intents)}. Lessons accepted {counts['accepted']}, "
      f"proposed {counts['proposed']}, disputed {counts['disputed']}. Sources: {len(state['sources'])}.")
    w("")

    w("## Standing direction")
    w("")
    if not current:
        w("(none)")
        w("")
    for rec in current:
        flags = f" [{', '.join(rec['flags'])}]" if rec["flags"] else ""
        w(f"### {_md(_cut(rec['title'], 200))} ({rec['id']}){flags}")
        w("")
        # Provenance flags (observed-only, secondhand, open, ...) sit on every claim line, next to the text a
        # reader would act on, not only in the heading (Codex Q1 ruling, M21 phase 3).
        for cid in rec["claims"]:
            ref = f"{rec['id']}#{cid}"
            claim = claims[ref]
            if claim["status"] == "current":
                conf = " (confirmed)" if claim["confirmed"] else ""
                w(f"- {cid}: {_md(_cut(claim['text'], TEXT))}{conf}{flags}")
            else:
                head = claims.get(claim["head"])
                text = _md(_cut(head["text"], TEXT)) if head else "(revising claim not in log)"
                w(f"- {cid} now reads ({claim['head']}): {text}{flags}")
            for line in _links(ref, claims, records, sources=state["sources"], outgoing=outgoing):
                w(line)
        if rec.get("open"):
            later = sorted({link["from"].split("#")[0] for cid in rec["claims"]
                            for link in claims[f"{rec['id']}#{cid}"]["links"]
                            if link["rel"] in ("refines", "revises", "carries")} - {rec["id"]})
            note = f" (written at seq {rec['seq']}; later records on these claims: {', '.join(later)})" if later else ""
            w(f"- open: {_md(_cut(rec['open'], 300))}{note}")
        scope = bodies.get(rec["id"], {}).get("scope_note")
        if scope:
            w(f"- scope: {_md(_cut(scope, 300))}")
        for sid in rec["sources"]:
            src = state["sources"].get(sid)
            if src is None:
                w(f"- source {sid}: (not in log)")
                continue
            auth = (src.get("auth") or {}).get("channel") or "null"
            head = f"- source {sid} (seq {src['seq']}, {src['role']}, auth {auth}, {src['quote_source']})"
            data = None if src["redacted"] or source_bytes is None else source_bytes(sid)
            if src["redacted"] or (source_bytes is not None and data is None):
                w(head + ": [redacted]")
            elif data is not None:
                w(head + ": " + _md(_cut(data.decode("utf-8", "replace"), EXCERPT)))
            else:
                w(head)
        w("")

    w("## Lessons")
    w("")
    for status in ("accepted", "proposed", "disputed"):
        group = [r for r in lessons if r["status"] == status]
        w(f"### {status.capitalize()} ({len(group)})")
        w("")
        for rec in group:
            body = bodies.get(rec["id"], {})
            title = rec["title"] or _cut(rec["statement"], 80)
            w(f"- **{_md(_cut(title, 200))}** ({rec['id']})")
            w(f"  - statement: {_md(_cut(rec['statement'], TEXT))}")
            for field, label in (("applies_when", "applies when"), ("uncertainty", "uncertainty")):
                if body.get(field):
                    w(f"  - {label}: {_md(_cut(body[field], TEXT))}")
            refs = [str(ev["ref"]) for ev in body.get("evidence") or [] if isinstance(ev, dict) and ev.get("ref")]
            if refs:
                w(f"  - evidence: {_md(_cut(', '.join(refs), TEXT))}")
            if rec.get("disputed_with"):
                w(f"  - disputed with: {', '.join(rec['disputed_with'])}")
        if not group:
            w("(none)")
        w("")

    w("## History")
    w("")
    hist = []
    for ref, claim in claims.items():
        if claim["status"] == "superseded":
            hist.append((records[claim["record"]]["seq"], ref,
                         f"- claim {ref} superseded by {claim['head']}: {_md(_cut(claim['text'], 200))}"))
    for rec in intents:
        if rec["status"] != "current":
            hist.append((rec["seq"], rec["id"], f"- intent {rec['id']} {rec['status']}: {_md(_cut(rec['title'], 200))}"))
    for rec in lessons:
        if rec["status"] in ("superseded", "retired"):
            hist.append((rec["seq"], rec["id"], f"- lesson {rec['id']} {rec['status']}: "
                                                f"{_md(_cut(rec['title'] or rec['statement'], 200))}"))
    for _, _, line in sorted(hist):
        w(line)
    if not hist:
        w("(none)")
    w("")

    w("## Board backlog (open)")
    w("")
    rows = [r for r in state["backlog"].values() if r.get("status") not in ("done", "cancelled")]
    rows.sort(key=lambda r: (r.get("priority") if isinstance(r.get("priority"), int) else 99, r["seq"]))
    for r in rows:
        line = f"- {_md(_cut(r.get('title'), 160))} ({r['owner']}, {r.get('status')})"
        if r.get("blocked_by"):
            line += f"; blocked by {_md(', '.join(str(b) for b in r['blocked_by']))}"
        w(line)
    if not rows:
        w("(none)")
    w("")
    return "\n".join(out)
